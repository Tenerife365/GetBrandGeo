begin;
set local lock_timeout = '5s';  -- on a timeout the whole transaction aborts cleanly; this file is safe to run again

-- 1. Table. Every constraint inline, so a second run changes nothing.
create table if not exists public.client_invite_links (
  id               bigint generated always as identity primary key,
  user_id          uuid        not null references auth.users(id) on delete cascade,
  client_id        integer     not null references public.clients(id) on delete cascade,
  token_hash       text        not null unique
                               check (token_hash ~ '^[0-9a-f]{64}$'),
  source           text        not null
                               check (source in ('onboard-client', 'explee-import', 'resend-invite')),
  created_by       uuid        null,   -- the admin's auth id; null for the lead import. No FK on purpose.
  created_at       timestamptz not null default now(),
  expires_at       timestamptz not null,
  revoked_at       timestamptz null,
  revoked_reason   text        null
                               check (revoked_reason is null or revoked_reason in ('superseded', 'send_failed', 'revoked')),
  accepted_at      timestamptz null,
  last_redeemed_at timestamptz null,
  redeem_count     integer     not null default 0
                               check (redeem_count >= 0),
  constraint client_invite_links_expiry_check
    check (expires_at > created_at and expires_at <= created_at + interval '30 days'),
  constraint client_invite_links_revoked_pair_check
    check ((revoked_at is null) = (revoked_reason is null))
);

-- 2. Indexes. At most one active link per user (neither revoked nor accepted);
-- the list read by user; the client cascade.
create unique index if not exists client_invite_links_one_active
  on public.client_invite_links (user_id)
  where revoked_at is null and accepted_at is null;
create index if not exists client_invite_links_user_idx
  on public.client_invite_links (user_id, created_at desc);
create index if not exists client_invite_links_client_idx
  on public.client_invite_links (client_id);

-- 3. Security. RLS on with NO policy: only the service role (which bypasses
-- RLS) reads or writes this table, from the Netlify functions. No grant to
-- anon or authenticated, on the table or on its identity sequence. The
-- service role gets select, insert and update and NO delete: rows leave only
-- by the two cascades (Supabase's default privileges grant it delete on a new
-- table, hence the explicit revoke). TRUNCATE is revoked as well (server
-- review INFO-5), so no client of the service role can empty the table either.
alter table public.client_invite_links enable row level security;
revoke all on public.client_invite_links from anon, authenticated;
revoke all on sequence public.client_invite_links_id_seq from anon, authenticated;
revoke delete on public.client_invite_links from service_role;
revoke truncate on public.client_invite_links from service_role;
grant select, insert, update on public.client_invite_links to service_role;

comment on table public.client_invite_links is
  'BrandGEO 7 day invite links: sha256 of the emailed token only, never the token or an address. '
  'Written by netlify/functions/_invite_link.js and invite-redeem.js with the service role. '
  'Spec: docs/arch/invite-link-7-days.md.';

commit;

