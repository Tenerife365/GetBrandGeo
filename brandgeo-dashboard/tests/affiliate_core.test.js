const assert = require('assert')
const path = require('path')
const core = require(path.join(__dirname, '..', 'netlify', 'functions', '_affiliate_core.js'))

let passed = 0
const ok = (n) => { passed++; console.log('  ok -', n) }
const section = (n) => console.log(`\n${n}`)

section('money: integers only, no floats')
assert.strictEqual(core.majorToCents('12.50'), 1250)
assert.strictEqual(core.majorToCents('299'), 29900)
assert.strictEqual(core.majorToCents('0.1'), 10)
assert.strictEqual(core.majorToCents('1,5'), 150)
assert.strictEqual(core.majorToCents('12.505'), null)
assert.strictEqual(core.majorToCents('abc'), null)
assert.strictEqual(core.centsToMajor(5980), '59.80')
assert.strictEqual(core.centsToMajor(5), '0.05')
assert.strictEqual(core.parseCents(29900), 29900)
assert.strictEqual(core.parseCents('29900'), 29900)
assert.strictEqual(core.parseCents(1.5), null)
assert.strictEqual(core.parseCents(-1), null)
ok('majorToCents / centsToMajor / parseCents round-trip without floating point')
assert.strictEqual(core.percentOf(29900, 2000), 5980)
assert.strictEqual(core.percentOf(1, 5000), 1, 'half a cent rounds up')
assert.strictEqual(core.percentOf(3, 3333), 1)
