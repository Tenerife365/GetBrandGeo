d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming')
assert.deepStrictEqual(d.flags, ['duplicate_customer'])
ok('last touch: the newest link wins and the switch is flagged')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'first_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'existing')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-11-10T00:00:00Z' }, mode: 'first_touch', now: '2026-11-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming', 'an expired first touch no longer holds the customer')
ok('first touch: the first link keeps the customer until its window expires')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'first_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming')
d = core.decideAttribution({ existing: { ...existing, source: 'coupon' }, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
ok('a coupon code overrides a link in both modes')
d = core.decideAttribution({ existing: { ...existing, source: 'manual' }, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
d = core.decideAttribution({ existing: { ...existing, source: 'coupon' }, incoming: { membership_id: 'm2', source: 'manual', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'incoming')
ok('a manual attribution beats everything, in both directions')
d = core.decideAttribution({ existing: { ...existing, converted_at: '2026-09-05T00:00:00Z' }, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
ok('a customer who already bought stays with the affiliate who brought the first sale')

