section('redirect URL')
let u = new URL(core.buildRedirectUrl({ destination: 'https://getbrandgeo.com/', code: 'DANIEL10', visitToken: 'abc123def456', programSlug: 'brandgeo', attributionDays: 30, incomingQuery: {} }))
assert.strictEqual(u.searchParams.get('ref'), 'DANIEL10')
assert.strictEqual(u.searchParams.get('bg_rid'), 'abc123def456')
assert.strictEqual(u.searchParams.get('ref_days'), '30')
assert.strictEqual(u.searchParams.get('utm_source'), 'affiliate')
assert.strictEqual(u.searchParams.get('utm_medium'), 'referral')
assert.strictEqual(u.searchParams.get('utm_campaign'), 'brandgeo')
ok('ref, bg_rid, ref_days and the three UTMs are added')
u = new URL(core.buildRedirectUrl({ destination: 'https://getbrandgeo.com/pricing?plan=growth', code: 'X1', visitToken: 't', programSlug: 'brandgeo', attributionDays: 30, incomingQuery: { utm_campaign: 'newsletter-sept', utm_content: 'hero', ref: 'INJECTED' } }))
assert.strictEqual(u.searchParams.get('plan'), 'growth', 'destination query preserved')
assert.strictEqual(u.searchParams.get('utm_campaign'), 'newsletter-sept', 'partner UTM wins')
assert.strictEqual(u.searchParams.get('utm_content'), 'hero', 'other params pass through')
assert.strictEqual(u.searchParams.get('ref'), 'X1', 'an injected ref on the click cannot override the real code')
ok('existing UTMs are preserved and the affiliate cannot forge ref via the click query')
assert.strictEqual(core.isSafeDestination('https://example.com/x'), true)
assert.strictEqual(core.isSafeDestination('javascript:alert(1)'), false)
assert.strictEqual(core.isSafeDestination('not a url'), false)
ok('only http(s) destinations are accepted')

