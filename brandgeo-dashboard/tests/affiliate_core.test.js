section('conversion input validation')
let v = core.validateConversionInput({ idempotency_key: 'order_1', conversion_type: 'sale', amount: '299.00', currency: 'eur', customer_email: 'A@B.com', metadata: { a: 1 } })
assert.deepStrictEqual(v.errors, [])
assert.strictEqual(v.row.amount_cents, 29900)
assert.strictEqual(v.row.currency, 'EUR')
assert.strictEqual(v.row.customer_email, 'a@b.com')
assert.strictEqual(v.row.status, 'confirmed')
v = core.validateConversionInput({ idempotency_key: 'order_2', conversion_type: 'sale', amount_cents: 12.5 })
assert.ok(v.errors.some((e) => /amount_cents/.test(e)))
v = core.validateConversionInput({ conversion_type: 'nope' })
assert.ok(v.errors.some((e) => /idempotency_key/.test(e)))
assert.ok(v.errors.some((e) => /conversion_type/.test(e)))
v = core.validateConversionInput({ idempotency_key: 'k', conversion_type: 'sale', commission: '999.00' })
assert.strictEqual(v.row.commission, undefined, 'a commission sent by the client is ignored')
const big = { blob: 'x'.repeat(5000) }
v = core.validateConversionInput({ idempotency_key: 'k', conversion_type: 'sale', metadata: big })
assert.deepStrictEqual(v.row.metadata, { truncated: true })
ok('validateConversionInput accepts major or cents, normalises, ignores client commissions, caps metadata')

section('program input validation')
v = core.validateProgramInput({ slug: 'Bad Slug', name: '', destination_url: 'ftp://x' })
assert.strictEqual(v.errors.length, 3)
v = core.validateProgramInput({ slug: 'brandgeo', name: 'BrandGEO', destination_url: 'https://getbrandgeo.com/', sale_commission_bps: 2000, recurring_months: '' })
assert.deepStrictEqual(v.errors, [])
assert.strictEqual(v.row.recurring_months, null)
v = core.validateProgramInput({ sale_commission_bps: 20000 }, { partial: true })
assert.ok(v.errors[0].includes('sale_commission_bps'))
ok('program validation rejects bad slugs, urls and out-of-range rates; partial patches skip required fields')
v = core.validateCustomRules({ sale_commission_bps: 2500, bogus: 1 })
assert.deepStrictEqual(v.errors, [])
assert.deepStrictEqual(v.rules, { sale_commission_bps: 2500 })
ok('custom rules keep only known keys')

