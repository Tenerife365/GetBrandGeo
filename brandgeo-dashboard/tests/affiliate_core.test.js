section('commission rules')
const program = { currency: 'EUR', lead_commission_cents: 0, sale_commission_type: 'percent', sale_commission_cents: 0, sale_commission_bps: 2000, recurring_commission_bps: 2000, recurring_months: 12, attribution_days: 30, approval_days: 30, attribution_mode: 'last_touch' }
let rules = core.effectiveRules(program, null)
let r = core.computeCommission({ rules, conversionType: 'sale', amountCents: 29900, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 5980)
assert.strictEqual(r.snapshot.rule, 'percent_of_sale')
ok('20% of EUR 299.00 is EUR 59.80')
r = core.computeCommission({ rules, conversionType: 'lead', amountCents: 0, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 0)
assert.strictEqual(r.reason, 'lead_not_commissionable')
ok('a raw lead earns nothing')
const leadProgram = { ...program, lead_commission_cents: 10000, sale_commission_type: 'fixed', sale_commission_cents: 50000, recurring_commission_bps: 0 }
rules = core.effectiveRules(leadProgram, null)
r = core.computeCommission({ rules, conversionType: 'qualified_lead', amountCents: 0, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 10000)
r = core.computeCommission({ rules, conversionType: 'sale', amountCents: 123456, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 50000)
assert.strictEqual(r.snapshot.rule, 'fixed_per_sale')
r = core.computeCommission({ rules, conversionType: 'recurring', amountCents: 29900, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 0)
assert.strictEqual(r.reason, 'one_time_commission_only')
ok('fixed per qualified lead, fixed per sale, and no recurring when the program is one-time')

rules = core.effectiveRules(program, { custom_rules: { sale_commission_bps: 2500 } })
r = core.computeCommission({ rules, conversionType: 'sale', amountCents: 29900, occurredAt: '2026-09-12T00:00:00Z' })
assert.strictEqual(r.amountCents, 7475)
assert.strictEqual(r.snapshot.custom, true)
assert.strictEqual(rules.recurring_commission_bps, 2000, 'keys not overridden keep the program value')
ok('a custom per-affiliate rate overrides only the keys it sets')

rules = core.effectiveRules(program, null)
const firstSale = '2026-01-15T10:00:00Z'
const until = core.recurringUntil(rules, firstSale)
assert.strictEqual(until.toISOString(), '2027-01-15T10:00:00.000Z')
r = core.computeCommission({ rules, conversionType: 'recurring', amountCents: 29900, occurredAt: '2026-12-15T10:00:00Z', attribution: { recurring_until: until.toISOString() } })
assert.strictEqual(r.amountCents, 5980)
r = core.computeCommission({ rules, conversionType: 'recurring', amountCents: 29900, occurredAt: '2027-02-15T10:00:00Z', attribution: { recurring_until: until.toISOString() } })
assert.strictEqual(r.amountCents, 0)
assert.strictEqual(r.reason, 'recurring_window_ended')
r = core.computeCommission({ rules, conversionType: 'recurring', amountCents: 29900, occurredAt: '2026-12-15T10:00:00Z', attribution: { recurring_until: until.toISOString(), subscription_ended_at: '2026-11-01T00:00:00Z' } })
assert.strictEqual(r.reason, 'subscription_ended')
assert.strictEqual(core.recurringUntil({ ...rules, recurring_months: null }, firstSale), null, 'null months = unlimited')
ok('recurring pays inside the 12-month window from the first sale and stops after it or after cancellation')

assert.strictEqual(core.approveAfter('2026-09-12T00:00:00Z', 30).toISOString(), '2026-10-12T00:00:00.000Z')
ok('approval delay defaults to 30 days after the sale')
assert.strictEqual(core.summarizeRules(program), '20% of every payment for the first 12 months')
assert.strictEqual(core.summarizeRules(leadProgram), 'EUR 500.00 per sale, plus EUR 100.00 per qualified lead')
ok('summarizeRules produces the plain-English line the public page shows')

section('attribution policy')
let d = core.decideAttribution({ existing: null, incoming: { membership_id: 'm1', source: 'link', at: '2026-09-01T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'incoming')
const existing = { membership_id: 'm1', source: 'link', last_touch_at: '2026-09-01T00:00:00Z', expires_at: '2026-10-01T00:00:00Z', converted_at: null }
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming')
assert.deepStrictEqual(d.flags, ['duplicate_customer'])
ok('last touch: the newest link wins and the switch is flagged')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'first_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'existing')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'link', at: '2026-11-10T00:00:00Z' }, mode: 'first_touch', now: '2026-11-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming', 'an expired first touch no longer holds the customer')
ok('first touch: the first link keeps the customer until its window expires')
d = core.decideAttribution({ existing, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'first_touch', now: '2026-09-10T00:00:00Z' })
assert.strictEqual(d.winner, 'incoming')
d = core.decideAttribution({ existing: { ...existing, source: 'coupon' }, incoming: { membership_id: 'm2', source: 'link', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
ok('a coupon code overrides a link in both modes')
d = core.decideAttribution({ existing: { ...existing, source: 'manual' }, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
d = core.decideAttribution({ existing: { ...existing, source: 'coupon' }, incoming: { membership_id: 'm2', source: 'manual', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'incoming')
ok('a manual attribution beats everything, in both directions')
d = core.decideAttribution({ existing: { ...existing, converted_at: '2026-09-05T00:00:00Z' }, incoming: { membership_id: 'm2', source: 'coupon', at: '2026-09-10T00:00:00Z' }, mode: 'last_touch' })
assert.strictEqual(d.winner, 'existing')
ok('a customer who already bought stays with the affiliate who brought the first sale')

section('self-referral detection')
const aff = { email: 'partner@agency-example.com', website: 'https://agency-example.com', email_hash: core.hashEmail('partner@agency-example.com') }
assert.strictEqual(core.isSelfReferral({ affiliate: aff, customerEmail: 'partner@agency-example.com' }), true)
assert.strictEqual(core.isSelfReferral({ affiliate: aff, customerEmail: 'boss@agency-example.com' }), true, 'same private domain')
assert.strictEqual(core.isSelfReferral({ affiliate: aff, customerEmail: 'ceo@shop.agency-example.com' }), true, 'subdomain of the affiliate website')
assert.strictEqual(core.isSelfReferral({ affiliate: aff, customerEmail: 'someone@example.org' }), false)
assert.strictEqual(core.isSelfReferral({ affiliate: { ...aff, email: 'p@gmail.com', website: null }, customerEmail: 'q@gmail.com' }), false, 'public mail domains do not count')
assert.strictEqual(core.isSelfReferral({ affiliate: aff, customerEmailHash: aff.email_hash }), true, 'hash-only match')
ok('self-referrals are flagged by email, private domain, website domain, or hash')

section('commission state machine')
assert.strictEqual(core.canTransition('pending', 'approved'), true)
assert.strictEqual(core.canTransition('pending', 'paid'), false)
assert.strictEqual(core.canTransition('approved', 'payable'), true)
assert.strictEqual(core.canTransition('payable', 'paid'), true)
