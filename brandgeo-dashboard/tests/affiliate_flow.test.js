  assert.ok(r.body.conversions.every((c) => c.affiliate_email))
  r = await adminPost({ action: 'visits.list', program_id: P2.id })
  assert.ok(r.body.visits.length >= 2 && r.body.visits.every((v) => v.program_id === P2.id))
  ok('list actions filter by program and type and decorate rows with affiliate names')
  const deletes = db.calls.filter((c) => c.op === 'delete')
  assert.ok(deletes.every((c) => c.table === 'affiliate_payout_items'), `unexpected delete on ${JSON.stringify(deletes)}`)
  assert.ok(rows('affiliate_conversions').length >= 12)
  assert.ok(rows('affiliate_attributions').length >= 5)
