  ok('Ana attaches an invoice to her own payout; executables and other affiliates are refused')
  r = await call(portal, env.post({ action: 'update_payout', payout_method: 'paypal', payout_details: { email: 'ana-pay@partner-a.example.com', card_number: '4111', password: 'x' } }, { token: 'ana-jwt' }))
