  r = await call(portal, env.post({ action: 'upload_url', batch_id: batch.id, filename: 'invoice sept.pdf' }, { token: 'ana-jwt' }))
  assert.strictEqual(r.status, 200)
  assert.ok(r.body.path.startsWith(`${ana.id}/${batch.id}/`))
